#!/usr/bin/env python3
"""Generate generated-plugins/ammo/hooks/hooks.json (conventions §7).

Input: the `hooks` block of ammo-server ai_cli_session/.claude/settings.local.json.
Rules, applied in order:
  1. Keep a hook whose script is in KEEP; skip one in DROP; stop on any other
     script so a new source hook forces a keep-or-drop decision.
  2. Rewrite `$CLAUDE_PROJECT_DIR/.claude/hooks/X` to `"${CLAUDE_PLUGIN_ROOT}/hooks/X"`.
  3. Drop groups left empty. The statusLine block is not a hook and is not read.
  4. Append FRONTMATTER: the auditor's two hooks from agents/ammo-auditor.md.
     Plugin agents ignore `hooks` frontmatter, so they move here. A frontmatter
     Stop hook runs as SubagentStop; the matcher keeps it on the auditor only.

    python3 gen_hooks_json.py              write the plugin's hooks/hooks.json
    python3 gen_hooks_json.py --out FILE   write FILE instead
    python3 gen_hooks_json.py --check      exit 1 when hooks.json differs

Exit 3 when the source settings file is missing. stdlib only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SOURCE = Path("/Users/jinhun/GitHub/ammo-server/ai_cli_session/.claude/settings.local.json")
OUT = Path(__file__).resolve().parents[2] / "generated-plugins" / "ammo" / "hooks" / "hooks.json"
SOURCE_COMMAND = re.compile(r"\$CLAUDE_PROJECT_DIR/\.claude/hooks/([\w.-]+)")
NEW_COMMAND = '"${{CLAUDE_PLUGIN_ROOT}}/hooks/{}"'

# team-spawn-guard stays: it enforces the SKILL.md team-member-vs-subagent contract.
KEEP = (
    "ammo-msg-check.sh", "ammo-team-spawn-guard.sh", "ammo-pretool-guard.sh",
    "ammo-skill-files-guard.sh", "ammo-env-default-guard.sh", "worktree-create-with-build.sh",
    "ammo-precompact.sh", "ammo-postcompact.sh", "ammo-stop-guard.sh", "ammo-subagent-release.sh",
    "ammo-gpu-release.sh", "ammo-monitor-reminder.sh", "ammo-audit-start-stamp.sh",
    "ammo-state-validate.sh", "ammo-next-step-reminder.sh", "ammo-artifact-layout-warn.sh",
    "worktree-remove-cleanup.sh",
)
DROP = (
    "ammo-venv-python-guard.sh", "ammo-pip-guard.sh", "ammo-agent-cwd-guard.sh",
    "ammo-msg-mirror.sh",
)
# (event, matcher, script, timeout seconds). The frontmatter said 5000, meant as ms.
FRONTMATTER = (
    ("PostToolUse", "Write", "inject-audit-phase2.sh", 5),
    ("SubagentStop", "^(ammo:)?ammo-auditor$", "audit-phase2-guard.sh", 5),
)
DESCRIPTION = (
    "AMMO campaign hooks for Claude Code. A hook acts only inside a campaign, the dir "
    "<engine>/.ammo/<campaign-id>/ that the .ammo/active marker or AMMO_ARTIFACT_DIR names. "
    "Outside a campaign every hook exits 0 and prints nothing. The two worktree hooks "
    "cannot decline, so they act outside a campaign too: WorktreeCreate makes a plain git "
    "worktree and prints its path, and WorktreeRemove removes that worktree and its branch. "
    "Generated by planning-records/ammo/gen_hooks_json.py from the ammo-server hook "
    "registrations. Do not edit by hand."
)


def generate(settings: dict) -> dict:
    hooks: dict = {}
    for event, groups in settings["hooks"].items():
        for group in groups:
            kept = []
            for hook in group["hooks"]:
                match = SOURCE_COMMAND.fullmatch(hook.get("command", ""))
                if not match:
                    raise SystemExit(f"unexpected hook command: {hook.get('command')!r}")
                script = match.group(1)
                if script in DROP:
                    continue
                if script not in KEEP:
                    raise SystemExit(f"{script} is in neither KEEP nor DROP (conventions §7)")
                kept.append({**hook, "command": NEW_COMMAND.format(script)})
            if kept:
                hooks.setdefault(event, []).append({**group, "hooks": kept})
    for event, matcher, script, timeout in FRONTMATTER:
        hook = {"type": "command", "command": NEW_COMMAND.format(script), "timeout": timeout}
        hooks.setdefault(event, []).append({"matcher": matcher, "hooks": [hook]})
    registered = {h["command"] for groups in hooks.values() for g in groups for h in g["hooks"]}
    missing = [s for s in KEEP if NEW_COMMAND.format(s) not in registered]
    if missing:
        raise SystemExit(f"KEEP hooks the source does not register: {missing}")
    return {"description": DESCRIPTION, "hooks": hooks}


def render(settings: dict) -> str:
    return json.dumps(generate(settings), indent=2, ensure_ascii=True) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if not args.source.is_file():
        print(f"source settings not found: {args.source}", file=sys.stderr)
        return 3
    text = render(json.loads(args.source.read_text(encoding="utf-8")))
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        if current != text:
            print(f"{args.out} is stale; rerun {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
